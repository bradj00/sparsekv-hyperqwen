#!/usr/bin/env python3
"""runtime_tables.py [runtime.csv] [RUNTIME.md] -- totals and the per-job table for RUNTIME.md from runtime.csv."""
import collections, csv, os, sys
from datetime import datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "runtime.csv")
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "RUNTIME.md")
rows = list(csv.DictReader(open(src)))
H = lambda xs: sum(float(r["wall_secs"]) for r in xs) / 3600  # noqa: E731
BOOT = lambda xs: sum(float(r["server_boot_secs"] or 0) for r in xs) / 3600  # noqa: E731
GPU = {"0": "GPU0 (RTX 3090 Ti, PCIe x16)", "1": "GPU1 (RTX 3090, PCIe x4)"}
bench = [r for r in rows if r["suite"] != "kld"]
kld = [r for r in rows if r["suite"] == "kld"]


def ts(s):
    return datetime.strptime(s, "%Y-%m-%dT%H:%M:%SZ")


def span(xs, use_server=True):
    a = min((r["server_start_utc"] or r["start_utc"]) if use_server else r["start_utc"] for r in xs)
    b = max(r["end_utc"] for r in xs)
    return a, b, (ts(b) - ts(a)).total_seconds() / 3600


md = ["# Runtime of every job", "",
      "Generated by `harness/runtime_tables.py` from [`runtime.csv`](runtime.csv) (one row per job instance; do not "
      "edit by hand). GPU0 = RTX 3090 Ti (PCIe x16), GPU1 = RTX 3090 (PCIe x4), both 24 GB at a 250 W cap. "
      "**GPU-hours = wall time of the client run** (first request to last answer, `wall_secs`), excluding server "
      "boot; boot time is listed separately. One server ran per GPU at a time, so GPU-hours are also GPU occupancy.", "",
      "Sources (`source` column): `stats` = the runner's per-job stats file (secs, items done/errors); `runner-log` = "
      "reconstructed from the runner's own log for runs that left no stats file (crashed, interrupted, duplicate or "
      "aborted starts; end = next runner event); `event-log` = item counts from LOG.md; `kld-log` = the KLD stage "
      "runner's log (start = server healthy).", ""]

a, b, hrs = span(bench)
ka, kb, khrs = span(kld)
md += ["## Totals", "",
       f"- Job instances: **{len(rows)}** ({len(bench)} benchmark-queue runs incl. "
       f"{sum(1 for r in bench if r['note'].startswith('crashed'))} crashed runs (all re-run), "
       f"{sum(1 for r in bench if 'boot failure' in r['job'])} boot failures, "
       f"{sum(1 for r in bench if r['note'].startswith(('duplicate', 'aborted', 'interrupted')))} duplicate/aborted/interrupted starts; "
       f"plus {len(kld)} KLD stages).",
       f"- Benchmark queue wall-clock span: **{a} -> {b}** ({hrs:.1f} h, first server boot to last finished job; "
       "the main benchmark ended 2026-11-04T00:27Z, the rest are post-benchmark S6 tests).",
       f"- KLD stages: {ka} -> {kb} (two sessions: 2026-11-02 04:42-05:57Z before the benchmark, 2026-11-03 20:12-21:35Z on GPU0 during it).",
       f"- Whole campaign (first KLD stage to last job): {min(a, ka)} -> {max(b, kb)} "
       f"({(ts(max(b, kb)) - ts(min(a, ka))).total_seconds() / 3600:.1f} h).",
       f"- **GPU-hours, all jobs: {H(rows):.1f} h** (+ {BOOT(rows):.1f} h server boots).", "",
       "| GPU | benchmark jobs (h) | KLD (h) | total (h) | server boots (h) | jobs |", "|---|---|---|---|---|---|"]
for g in ("0", "1"):
    bx = [r for r in bench if r["gpu"] == g]
    kx = [r for r in kld if r["gpu"] == g]
    md.append(f"| {GPU[g]} | {H(bx):.2f} | {H(kx):.2f} | {H(bx) + H(kx):.2f} | {BOOT(bx) + BOOT(kx):.2f} | {len(bx) + len(kx)} |")
md.append(f"| **both** | {H(bench):.2f} | {H(kld):.2f} | {H(rows):.2f} | {BOOT(rows):.2f} | {len(rows)} |")


def group(key, title):
    d = collections.defaultdict(list)
    for r in rows:
        d[r[key]].append(r)
    out = ["", f"### GPU-hours by {title}", "", f"| {title} | GPU0 (h) | GPU1 (h) | total (h) | jobs | items done |",
           "|---|---|---|---|---|---|"]
    for k in sorted(d, key=lambda k: -H(d[k])):
        x = d[k]
        items = sum(int(r["items_done"]) for r in x if r["items_done"] not in ("", None))
        out.append(f"| {k} | {H([r for r in x if r['gpu'] == '0']):.2f} | {H([r for r in x if r['gpu'] == '1']):.2f} | "
                   f"{H(x):.2f} | {len(x)} | {items} |")
    return out


md += group("suite", "suite")
md += group("variant", "variant")
md += group("config_dir", "config dir")
md += ["", "## Every job", "",
       "Times UTC. `boot` = server boot seconds when the job started a new server (blank = reused the running server). "
       "Items = done / errors (skipped = already present from an earlier run of the same job).", "",
       "| GPU | job | suite | config dir | variant | shard | conc | items | wall (s) | start | end | boot (s) | note |",
       "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    items = "" if r["items_done"] == "" else f"{r['items_done']} / {r['items_err']}" + (
        f" (skip {r['items_skipped']})" if r["items_skipped"] not in ("", "0") else "")
    md.append(f"| {r['gpu']} | {r['job']} | {r['suite']} | {r['config_dir']} | {r['variant']} | {r['shard']} | {r['conc']} | "
              f"{items} | {float(r['wall_secs']):.0f} | {r['start_utc'][5:-1].replace('T', ' ')} | "
              f"{r['end_utc'][5:-1].replace('T', ' ')} | {r['server_boot_secs']} | {r['note']} |")
open(dst, "w").write("\n".join(md) + "\n")
print("wrote", dst)
